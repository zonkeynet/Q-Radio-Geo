// The service worker's manifest: sw-manifest.json lists every file the worker may keep (content hash and size), and
// which of them it stores at install (the app shell); sw.js carries the manifest's own hash, so any published change
// makes browsers install the new worker, which fetches only the files whose hash changed.
//
//   node scripts/build_sw.mjs            rewrite the modulepreload list of index.html (scripts/build_preload.mjs),
//                                        then sw-manifest.json and the MANIFEST_HASH line of sw.js
//   node scripts/build_sw.mjs --check    exit 1 if either is out of date (scripts/test_sw.mjs runs this)
//   node scripts/build_sw.mjs --root DIR a copy of the site outside git (the browser test's versions)
//
// Run it after changing any file of the site (code, styles, data, images) and commit both files with the change.
// Hashes are of the bytes GitHub Pages serves: text files as committed (LF), whatever the checkout's line endings.
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { updatedIndex } from './build_preload.mjs';

const arg = name => { const i = process.argv.indexOf(name); return i < 0 ? null : process.argv[i + 1]; };
const ROOT = resolve(arg('--root') || join(dirname(fileURLToPath(import.meta.url)), '..'));
const CHECK = process.argv.includes('--check');

/** Files the worker may keep: the page, its code, styles, images and data. Not db/ (downloads), tests, docs or scripts. */
export const IN_SCOPE = /^(index\.html|manifest\.webmanifest|app-config\.json|(assets|js|vendor|data)\/.+)$/;
/** Stored at install, so a repeat visit needs no file from the network: the page, code, styles, icons, the default
 * theme's bundled texture (both WebP sizes, js/globe.mjs textureFile) and the small start-up data. Large data (places, stations, layers, tiles) is kept when the
 * page first asks for it. */
export const SHELL = [
    /^index\.html$/, /^manifest\.webmanifest$/, /^app-config\.json$/,
    /^assets\/(app|native-app)\.css$/, /^assets\/icons\/(icon\.svg|icon-192\.png|apple-touch-icon\.png)$/,
    /^js\/[a-z0-9.-]+\.m?js$/, /^vendor\/globe\.gl-[0-9.]+\.min\.js$/,
    /^assets\/textures\/earth-night(-2k)?\.webp$/,
    /^data\/(countries|summary)\.json$/
];
export const hash = bytes => createHash('sha256').update(bytes).digest('hex').slice(0, 16);

function listFiles(root) {
    if (existsSync(join(root, '.git'))) {
        const git = (...a) => execFileSync('git', ['-C', root, ...a], { maxBuffer: 1 << 28 }).toString();
        const eol = new Map(git('ls-files', '--eol', '-z').split('\0').filter(Boolean).map(l => { const [info, path] = l.split('\t'); return [path, info]; }));
        const paths = [...new Set(git('ls-files', '--cached', '--others', '--exclude-standard', '-z').split('\0').filter(Boolean))];
        // A text file committed with LF may be checked out with CRLF (core.autocrlf): hash what git stores.
        const text = (path, bytes) => {
            const info = eol.get(path);
            if (info) return /i\/(lf|none)/.test(info) && !/attr\/-text/.test(info);
            return !bytes.includes(0) && /\.(html|mjs|js|css|json|svg|geojson|webmanifest|txt|md)$/.test(path);
        };
        return paths.filter(p => IN_SCOPE.test(p) && existsSync(join(root, p))).map(path => {
            let bytes = readFileSync(join(root, path));
            if (bytes.includes(13) && text(path, bytes)) bytes = Buffer.from(bytes.toString('latin1').replace(/\r\n/g, '\n'), 'latin1');
            return { path, bytes };
        });
    }
    const out = [];
    const walk = dir => {
        for (const name of readdirSync(dir)) {
            const full = join(dir, name);
            if (statSync(full).isDirectory()) walk(full);
            else {
                const path = relative(root, full).split(sep).join('/');
                if (IN_SCOPE.test(path)) out.push({ path, bytes: readFileSync(full) });
            }
        }
    };
    walk(root);
    return out;
}

export function buildManifest(root = ROOT) {
    const files = listFiles(root).sort((a, b) => a.path < b.path ? -1 : a.path > b.path ? 1 : 0);
    const manifest = {
        note: 'Generated by scripts/build_sw.mjs: the files the service worker may keep, [content hash, bytes]. Do not edit.',
        shell: files.filter(f => SHELL.some(r => r.test(f.path))).map(f => f.path),
        files: Object.fromEntries(files.map(f => [f.path, [hash(f.bytes), f.bytes.length]]))
    };
    const text = JSON.stringify(manifest, null, 0).replace(/\],"/g, '],\n"') + '\n';
    return { manifest, text, version: hash(Buffer.from(text)) };
}

const MARK = /^const MANIFEST_HASH = '[0-9a-f]*';.*$/m;
export function workerSource(root, version) {
    const source = readFileSync(join(root, 'sw.js'), 'utf8');
    if (!MARK.test(source)) throw new Error('sw.js has no MANIFEST_HASH line');
    return source.replace(MARK, `const MANIFEST_HASH = '${version}'; // scripts/build_sw.mjs`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    // The page lists its modules for preloading: that list first, since the manifest hashes the page.
    const index = updatedIndex(ROOT), indexStale = readFileSync(join(ROOT, 'index.html'), 'utf8').replace(/\r\n/g, '\n') !== index;
    if (indexStale && !CHECK) writeFileSync(join(ROOT, 'index.html'), index);
    const { manifest, text, version } = buildManifest(ROOT);
    const worker = workerSource(ROOT, version);
    const path = join(ROOT, 'sw-manifest.json');
    const sameText = (a, b) => a.replace(/\r\n/g, '\n') === b.replace(/\r\n/g, '\n');
    const stale = indexStale ? ['index.html (modulepreload list)'] : [];
    if (!existsSync(path) || !sameText(readFileSync(path, 'utf8'), text)) stale.push('sw-manifest.json');
    if (!sameText(readFileSync(join(ROOT, 'sw.js'), 'utf8'), worker)) stale.push('sw.js');
    if (CHECK) {
        if (stale.length) { console.error(`Out of date: ${stale.join(', ')}. Run: node scripts/build_sw.mjs`); process.exit(1); }
        console.log(`Service worker manifest current: ${Object.keys(manifest.files).length} files, ${manifest.shell.length} in the shell, version ${version}`);
    } else {
        if (stale.includes('sw-manifest.json')) writeFileSync(path, text);
        if (stale.includes('sw.js')) writeFileSync(join(ROOT, 'sw.js'), worker);
        const shellBytes = manifest.shell.reduce((n, p) => n + manifest.files[p][1], 0);
        console.log(`sw-manifest.json: ${Object.keys(manifest.files).length} files, shell ${manifest.shell.length} files (${(shellBytes / 1e6).toFixed(2)} MB), version ${version}${stale.length ? '' : ' (unchanged)'}`);
    }
}
